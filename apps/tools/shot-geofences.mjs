// Screenshots the Geofences list (with a drawn draft), the import panel and one geofence. Run: node tools/shot-geofences.mjs <geofenceId>
import { chromium } from "playwright";
if (!process.env.STAFF_EMAIL || !process.env.STAFF_PASSWORD) throw new Error("Needs STAFF_EMAIL and STAFF_PASSWORD (a staff account on the local stack)");
const out = process.env.OUT ?? "./tools/shots";
const [, , id] = process.argv;
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1600, height: 1000 } })).newPage();
page.on("pageerror", (e) => console.log("pageerror:", String(e).slice(0, 200)));
page.on("console", (m) => { if (m.type() === "error") console.log("console.error:", m.text().slice(0, 160)); });
await page.goto("http://localhost:3000/login", { waitUntil: "networkidle", timeout: 180000 });
await page.getByLabel("Email").fill(process.env.STAFF_EMAIL);
await page.getByLabel("Password").fill(process.env.STAFF_PASSWORD);
await page.getByRole("button", { name: "Sign in" }).click();
await page.waitForURL((u) => !u.pathname.startsWith("/login"), { timeout: 30000 });
await page.goto("http://localhost:3000/pricing/geofences", { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/geofences-list.png` });
await page.goto("http://localhost:3000/pricing/geofences?panel=new", { waitUntil: "networkidle" });
await page.waitForTimeout(2000);
const map = page.getByRole("img", { name: "Map of geofences" });
const box = await map.boundingBox();
for (const [x, y] of [[0.4, 0.4], [0.6, 0.38], [0.62, 0.6], [0.42, 0.62]]) await page.mouse.click(box.x + box.width * x, box.y + box.height * y);
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/geofences-draw.png` });
await page.goto("http://localhost:3000/pricing/geofences?panel=import", { waitUntil: "networkidle" });
await page.waitForTimeout(1000);
await page.screenshot({ path: `${out}/geofences-import.png` });
await page.goto(`http://localhost:3000/pricing/geofences/${id}`, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/geofence-one.png` });
await browser.close();
console.log("done");
