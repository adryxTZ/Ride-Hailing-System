#!/usr/bin/env bash
# Regenerates rider/src/assets/serviceIcons.ts from the PNGs in rider/assets/icons/services/.
# Metro needs static require() paths, so the map is generated rather than discovered at runtime.
# Run after adding/removing icon files (e.g. after apps/tools/gen-icons.py).
set -euo pipefail
cd "$(dirname "$0")/../rider"
DIR=assets/icons/services
OUT=src/assets/serviceIcons.ts
{
  echo "// GENERATED by apps/tools/sync-icons.sh — do not edit. Keys = catalogue icon names."
  echo "import type { ImageSourcePropType } from \"react-native\";"
  echo ""
  if ls "$DIR"/*.png >/dev/null 2>&1; then
    echo "export const serviceIcons: Record<string, ImageSourcePropType> = {"
    for f in "$DIR"/*.png; do
      n=$(basename "$f" .png)
      echo "  \"$n\": require(\"../../$f\"),"
    done
    echo "};"
  else
    echo "export const serviceIcons: Record<string, ImageSourcePropType> = {};"
  fi
} > "$OUT"
echo "wrote $OUT ($(ls "$DIR"/*.png 2>/dev/null | wc -l | tr -d ' ') icons)"
